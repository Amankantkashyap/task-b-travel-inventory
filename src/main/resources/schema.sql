CREATE TABLE IF NOT EXISTS transactions (
  id UUID PRIMARY KEY,
  external_id VARCHAR(200) NOT NULL,
  type VARCHAR(20) NOT NULL CHECK (type IN ('flight','hotel','rail','navan_fee')),
  currency CHAR(3) NOT NULL,
  occurred_at VARCHAR(40) NOT NULL,
  total_minor BIGINT NOT NULL CHECK (total_minor >= 0),
  metadata JSON NOT NULL,
  CONSTRAINT uq_transactions_external_id UNIQUE (external_id)
);
CREATE TABLE IF NOT EXISTS transaction_taxes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id UUID NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  rate DECIMAL(20,10),
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0)
);
CREATE INDEX IF NOT EXISTS idx_transaction_taxes_parent ON transaction_taxes(transaction_id);
CREATE TABLE IF NOT EXISTS transaction_fees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id UUID NOT NULL REFERENCES transactions(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0)
);
CREATE INDEX IF NOT EXISTS idx_transaction_fees_parent ON transaction_fees(transaction_id);
CREATE TABLE IF NOT EXISTS invoices (
  id UUID PRIMARY KEY,
  currency CHAR(3) NOT NULL,
  total_minor BIGINT NOT NULL CHECK (total_minor >= 0)
);
CREATE TABLE IF NOT EXISTS invoice_lines (
  id UUID PRIMARY KEY,
  invoice_id UUID NOT NULL REFERENCES invoices(id) ON DELETE CASCADE,
  transaction_id UUID NOT NULL REFERENCES transactions(id),
  position INT NOT NULL,
  external_id VARCHAR(200) NOT NULL,
  type VARCHAR(20) NOT NULL,
  currency CHAR(3) NOT NULL,
  occurred_at VARCHAR(40) NOT NULL,
  total_minor BIGINT NOT NULL CHECK (total_minor >= 0),
  metadata JSON NOT NULL,
  CONSTRAINT uq_invoice_transaction UNIQUE(invoice_id, transaction_id),
  CONSTRAINT uq_invoice_position UNIQUE(invoice_id, position)
);
CREATE INDEX IF NOT EXISTS idx_invoice_lines_transaction ON invoice_lines(transaction_id);
CREATE TABLE IF NOT EXISTS invoice_taxes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id UUID NOT NULL REFERENCES invoice_lines(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  rate DECIMAL(20,10),
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0)
);
CREATE INDEX IF NOT EXISTS idx_invoice_taxes_line ON invoice_taxes(line_id);
CREATE TABLE IF NOT EXISTS invoice_fees (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  line_id UUID NOT NULL REFERENCES invoice_lines(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  amount_minor BIGINT NOT NULL CHECK (amount_minor >= 0)
);
CREATE INDEX IF NOT EXISTS idx_invoice_fees_line ON invoice_fees(line_id);
